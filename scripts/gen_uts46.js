// Writes browser_shield/uts46.txt: what a browser's host parser (UTS 46, nontransitional, as the WHATWG URL Standard
// asks) does with every non-ASCII code point, read from Node's own URL parser (ICU) rather than from a downloaded
// table. Python's idna codec uses Unicode 3.2 tables and keeps characters a browser drops (variation selectors,
// U+180F, U+2064), so a guard using it could be steered to a host it never checked.
//
//   node scripts/gen_uts46.js        rewrite the table
//   node scripts/gen_uts46.js --check exit 1 if the committed table differs (tests/test_urls.py runs this)
//
// Format, one entry per line, hex code points:
//   R <first> <last>   refused: the parser rejects a host containing it
//   M <cp> [<cp> ...]  mapped to that sequence (no sequence: dropped)
// Code points not listed pass through unchanged. Each code point is tried inside a label (x?y.example) and alone
// (?.example), and counts as refused only if both fail: a combining mark is invalid at a label's start, and a
// right-to-left letter fails the bidi rule next to Latin letters, yet both are fine in other labels.
const fs = require('fs');
const path = require('path');
const url = require('url');

const OUT = path.join(__dirname, '..', 'browser_shield', 'uts46.txt');

function probe(ch, before, after) {
  let host;
  try { host = new URL(`https://${before}${ch}${after}.example/`).hostname; } catch { return null; }
  const uni = url.domainToUnicode(host);
  const head = before;
  const tail = `${after}.example`;
  if (!uni.startsWith(head) || !uni.endsWith(tail)) return undefined; // composed with a neighbour: no single answer
  return uni.slice(head.length, uni.length - tail.length);
}

function build() {
  const lines = [`# generated by scripts/gen_uts46.js from Node ${process.version}, ICU ${process.versions.icu}, Unicode ${process.versions.unicode}`];
  let runStart = -1;
  let runEnd = -1;
  const flush = () => {
    if (runStart >= 0) lines.push(`R ${runStart.toString(16)} ${runEnd.toString(16)}`);
    runStart = -1;
  };
  for (let cp = 0x80; cp <= 0x10ffff; cp++) {
    if (cp >= 0xd800 && cp <= 0xdfff) continue;
    const ch = String.fromCodePoint(cp);
    let r = probe(ch, 'x', 'y');
    if (r === null || r === undefined) {
      const alone = probe(ch, '', '');
      if (alone !== null && alone !== undefined) r = alone;
      else if (r === undefined || alone === undefined) r = ch; // only composes: let NFC decide, as the browser does
    }
    if (r === null) {
      if (runStart >= 0 && cp === runEnd + 1) runEnd = cp;
      else if (runStart >= 0 && runEnd === 0xd7ff && cp === 0xe000) runEnd = cp;
      else { flush(); runStart = cp; runEnd = cp; }
      continue;
    }
    flush();
    if (r !== ch) lines.push(`M ${cp.toString(16)}${[...r].map((c) => ' ' + c.codePointAt(0).toString(16)).join('')}`);
  }
  flush();
  return lines.join('\n') + '\n';
}

const table = build();
if (process.argv.includes('--check')) {
  const committed = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  const strip = (s) => s.replace(/^#.*\n/, '');
  if (strip(committed) !== strip(table)) {
    console.error(`browser_shield/uts46.txt differs from what this Node (${process.versions.icu}) produces: rerun node scripts/gen_uts46.js`);
    process.exit(1);
  }
  console.log('uts46.txt matches');
} else {
  fs.writeFileSync(OUT, table);
  console.log(`wrote ${OUT}: ${table.split('\n').length - 2} entries`);
}
